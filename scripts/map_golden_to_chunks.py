def norm(text: str) -> str:
    """Lowercase and drop all whitespace (PDF extraction splits words randomly)."""
    return re.sub(r"\s+", "", text).lower()


def resolve(coll, quotes: dict[str, list[tuple[str, str]]]) -> dict[str, dict]:
    data = coll.get(include=["documents", "metadatas"])
    rows = [
        (cid, norm(doc), (meta or {}).get("source", ""))
        for cid, doc, meta in zip(
            data["ids"], data["documents"], data["metadatas"], strict=True
        )
    ]
    result: dict[str, dict] = {}
    for qid, items in quotes.items():
        ids: list[str] = []
        detail = []
        for source, quote in items:
            q = norm(quote)
            hits = [cid for cid, doc, src in rows if src.endswith(source) and q in doc]
            detail.append({"source": source, "quote": quote, "chunk_ids": hits})
            ids.extend(h for h in hits if h not in ids)
        result[qid] = {"chunk_ids": ids, "quotes": detail}
    return result


def write_golden(path: Path, mapping: dict[str, dict]) -> None:
    text = path.read_text(encoding="utf-8")
    crlf = "\r\n" in text
    text = text.replace("\r\n", "\n")
    for qid, info in mapping.items():
        ids = info["chunk_ids"][:3]
        block = re.compile(
            rf"(- id: {qid}\n(?:(?!\n  - id: ).)*?\n    chunk_ids: )\[[^\]\n]*\](?:  # [^\n]*)?",
            re.DOTALL,
        )
        text, n = block.subn(
            lambda m, ids=ids: m.group(1) + json.dumps(ids), text, count=1
        )
        if n != 1:
            raise SystemExit(f"could not update chunk_ids for {qid}")
    path.write_text(
        text.replace("\n", "\r\n") if crlf else text, encoding="utf-8", newline=""
    )


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    ap.add_argument("--host", default="localhost")
    ap.add_argument("--port", type=int, default=8001)
    ap.add_argument("--collection", default="rahbar_corpus")
    ap.add_argument("--out", default="")
    ap.add_argument("--write-golden", action="store_true")
    ap.add_argument("--golden", default="eval/golden.yaml")
    args = ap.parse_args()

    import chromadb

    coll = chromadb.HttpClient(host=args.host, port=args.port).get_collection(
        args.collection
    )
    mapping = resolve(coll, QUOTES)
    bad = [q for q, v in mapping.items() if not v["chunk_ids"]]
    for qid, v in mapping.items():
        print(f"{qid}: {len(v['chunk_ids'])} chunk(s) {v['chunk_ids'][:3]}")
    print(f"collection chunks: {coll.count()}")
    if args.out:
        Path(args.out).write_text(json.dumps(mapping, indent=2), encoding="utf-8")
    if args.write_golden:
        write_golden(Path(args.golden), mapping)
        print(f"wrote chunk_ids into {args.golden}")
    if bad:
        print(f"UNRESOLVED (no chunk contains the quote): {bad}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
